"""Render the evaluation report (``ml/reports/evaluation.json``) as Markdown.

Every number in the Markdown comes from the JSON produced by ``training.evaluate``.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any


def _f(v: Any, digits: int = 3) -> str:
    if v is None:
        return "—"
    if isinstance(v, float):
        return f"{v:.{digits}f}"
    return str(v)


def _pct(v: Any) -> str:
    return "—" if v is None else f"{100 * float(v):.1f}%"


def write_markdown(r: dict[str, Any], out: Path) -> None:
    sp = r["splits"]
    lq = r["label_quality"]
    prod = r["production"]
    sim = r.get("simulation", {})
    L: list[str] = []
    a = L.append
    a("# Evaluation report — Financial Fraud Detection Engine\n")
    a("Generated by `python -m app.cli evaluate`. **All data is synthetic** (`app/ml/synthetic.py`); these numbers")
    a("measure how learnable the simulator's fraud patterns are, not real-world performance.\n")
    a("## Data\n")
    a(
        f"- Simulation: {sim.get('customers')} customers, {sim.get('transactions'):,} transactions, "
        f"{sim.get('fraud_transactions'):,} fraudulent ({_pct(sim.get('fraud_rate'))}), seed {sim.get('seed')}"
    )
    a(f"- Fraud by scenario: {', '.join(f'{k} {v}' for k, v in (sim.get('fraud_by_scenario') or {}).items())}")
    a(
        f"- Deployment date D = {sp['deploy_at'][:10]}. Train: before D−60 days ({sp['train']['rows']:,} rows); "
        f"calibration: D−60…D−30 ({sp['calibration']['rows']:,}); test: after D ({sp['test']['rows']:,}, "
        f"{lq['test_true_fraud']} fraud)"
    )
    a(
        f"- Labels known at D for the training window: {lq['train_known_fraud_at_deploy']} of "
        f"{lq['train_true_fraud']} true frauds (the rest were never reported or reported later); "
        f"{lq['train_known_but_not_fraud']} wrongly disputed legitimate transactions are labelled fraud."
    )
    a("- Test labels are the simulator's **full ground truth**, including fraud that was never reported.\n")

    a("## Model comparison (test period, ground truth)\n")
    a(
        "| Model | CV PR-AUC (train, grouped by card) | Test PR-AUC | Test ROC-AUC | Recall at capacity | Precision at capacity |"
    )
    a("|---|---|---|---|---|---|")
    cv = r["cross_validation"]
    for name, m in r["test_models"].items():
        c = cv.get(name)
        cvs = f"{c['pr_auc_mean']:.3f} ± {c['pr_auc_std']:.3f}" if c else "—"
        cap = m.get("at_capacity") or {}
        a(
            f"| {name} | {cvs} | {_f(m['pr_auc'])} | {_f(m['roc_auc'])} | {_pct(cap.get('recall'))} | {_pct(cap.get('precision'))} |"
        )
    a(
        f"\nCapacity = {r['capacity_per_day']} reviews per day. Rules baseline = highest band forced by the default rules.\n"
    )
    a(
        f"Production algorithm (best cross-validated PR-AUC): **{r['production_algorithm']}**, Platt-calibrated on the calibration window.\n"
    )

    a("## Production model at its operating thresholds (test period)\n")
    t = prod["thresholds"]
    a(
        f"Thresholds (calibrated probability): medium ≥ {t['medium']:.4f}, high ≥ {t['high']:.4f}, critical ≥ {t['critical']:.4f}\n"
    )
    a("| Cut-off | Alerts/day | Precision | Recall | Dollar recall |")
    a("|---|---|---|---|---|")
    for label, k in (("high or above (reviewed)", "at_high"), ("critical", "at_critical")):
        m = prod[k]
        a(
            f"| {label} | {m['alerts_per_day']:.1f} | {_pct(m['precision'])} | {_pct(m['recall'])} | {_pct(m['dollar_recall'])} |"
        )
    w = prod["with_rules"]
    a(
        f"| model + rules (final band) | {w['alerts_per_day']:.1f} | {_pct(w['precision'])} | {_pct(w['recall'])} | {_pct(w['dollar_recall'])} |"
    )
    a(f"\nPR-AUC {_f(prod['pr_auc'])}, ROC-AUC {_f(prod['roc_auc'])}, Brier {_f(prod['brier'], 5)}.\n")

    a("### Recall by fraud scenario\n")
    a("| Scenario | Fraud txns in test | Recall (model ≥ high) | Recall (final band, with rules) |")
    a("|---|---|---|---|")
    for s, m in prod["recall_by_scenario"].items():
        a(f"| {s} | {m['fraud_transactions']} | {_pct(m['recall_model_high'])} | {_pct(m['recall_with_rules'])} |")
    a("\n`device_compromise` only starts in the test period (concept drift): the model never saw it in training.\n")

    a("### Calibration (reliability)\n")
    a("| Predicted bin | Transactions | Mean predicted | Observed fraud rate |")
    a("|---|---|---|---|")
    for b in prod["reliability"]:
        a(
            f"| {b['bin_low']:.2f}–{b['bin_high']:.2f} | {b['count']:,} | {b['mean_predicted']:.4f} | {b['observed_rate']:.4f} |"
        )
    a(
        "\nObserved rates use the full ground truth, which includes never-reported fraud the model was not trained on, "
        "so some under-prediction is expected.\n"
    )

    a("### Weekly performance in the test period\n")
    a("| Week | Transactions | Fraud | PR-AUC | Alert precision |")
    a("|---|---|---|---|---|")
    for wk in prod["weekly"]:
        a(
            f"| {wk['week'][:10]} | {wk['transactions']:,} | {wk['fraud']} | {_f(wk['pr_auc'])} | {_pct(wk['alert_precision'])} |"
        )

    a("\n## Drift (PSI vs. the calibration window)\n")
    a("| Month | Score PSI | Max feature PSI | Merchant-category mix PSI |")
    a("|---|---|---|---|")
    cat = r["drift"]["category_mix_psi_by_month"]
    for d in r["drift"]["by_month"]:
        a(f"| {d['month']} | {d['score_psi']:.3f} | {d['max_feature_psi']:.3f} | {cat.get(d['month'], 0):.3f} |")
    a(
        "\nPSI < 0.1 stable · 0.1–0.25 warning · > 0.25 alert. The digital-wallet adoption and `device_compromise` "
        "fraud begin in the final ~2 months.\n"
    )

    an = r["anomaly"]
    a("## Anomaly score (Isolation Forest, unsupervised)\n")
    a(f"- PR-AUC on all test fraud: {_f(an['pr_auc'])} (supervised model: {_f(prod['pr_auc'])})")
    a(
        f"- `device_compromise` vs. legitimate only: anomaly {_f(an.get('device_compromise_vs_legit_pr_auc'))}, "
        f"supervised model {_f(an.get('model_device_compromise_vs_legit_pr_auc'))}\n"
    )

    pit = r["validation_pitfalls"]
    a("## Validation pitfalls (what a careless setup would report)\n")
    a("| Setup | PR-AUC |")
    a("|---|---|")
    a(
        f"| This report: out-of-time test, point-in-time features, labels as known at D | {_f(pit['point_in_time_test_pr_auc'])} |"
    )
    if "leaky_merchant_rate_test_pr_auc" in pit:
        a(
            f"| Same, but merchant fraud rate computed with *future* labels (leak) | {_f(pit['leaky_merchant_rate_test_pr_auc'])} |"
        )
    a(
        f"| Random 75/25 split with perfect labels (ignores time and label delay) | {_f(pit['random_split_with_ground_truth_pr_auc'])} |"
    )
    a("\n## Most important features (mean |SHAP|, production model)\n")
    a("| Feature | Mean abs SHAP (log-odds) |")
    a("|---|---|")
    for g in prod["global_importance"]:
        a(f"| {g['feature']} | {g['mean_abs_shap']:.3f} |")
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
